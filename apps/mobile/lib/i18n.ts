export type TranslationKey = keyof typeof MESSAGES
export type TranslationParams = Record<string, number | string>

export function translate(
  language: Language,
  key: TranslationKey,
  params: TranslationParams = {}
) {
  return MESSAGES[key][language].replace(/\{([A-Za-z]+)\}/gu, (token, name) =>
    name in params ? String(params[name]) : token
  )
}

export function formatNumber(
  language: Language,
  value: number,
  options?: Intl.NumberFormatOptions
) {
  return new Intl.NumberFormat(LOCALE_TAGS[language], options).format(value)
}

const DIRECT_LANGUAGES: Readonly<Record<string, Language>> = {
  de: "de",
  en: "en",
  es: "es",
  fr: "fr",
  it: "it",
  ja: "ja",
  ko: "ko",
}

export function resolveLanguageTag(languageTag: string): Language {
  const [languageCode, ...subtags] = languageTag.replaceAll("_", "-").split("-")
  const code = languageCode?.toLowerCase()
  const normalizedSubtags = subtags.map((subtag) => subtag.toUpperCase())

  if (!code) return "en"
  if (code === "pt") return normalizedSubtags.includes("BR") ? "pt-BR" : "en"
  if (code === "zh") {
    return normalizedSubtags.some((subtag) =>
      ["HANS", "CN", "SG"].includes(subtag)
    )
      ? "zh-Hans"
      : "en"
  }

  return DIRECT_LANGUAGES[code] ?? "en"
}
